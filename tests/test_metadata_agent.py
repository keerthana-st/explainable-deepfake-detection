def test_corrupted_malformed_file_handling(agent):
    """
    Requirement 4: Test on deliberately corrupted/malformed files.
    Must fail gracefully with clear state, never crash the pipeline.
    """
    with tempfile.TemporaryDirectory() as tmpdir:
        # Corrupted JPEG header
        corrupt_jpg = Path(tmpdir) / "broken.jpg"
        with open(corrupt_jpg, "wb") as f:
            f.write(b"\xFF\xD8\xFF\xE1GARBAGE_BYTES_NO_LENGTH\x00\x00\xFF")

        res1 = agent.analyze(corrupt_jpg)
        assert res1.metadata_flag in [MetadataState.MISSING.value, MetadataState.PRESENT_NO_AI_SIGNAL.value]

        # Corrupted zero-byte file
        empty_file = Path(tmpdir) / "empty.png"
        empty_file.touch()
        res2 = agent.analyze(empty_file)
        assert res2.metadata_flag == MetadataState.MISSING.value

        # Non-existent file
        non_existent = Path(tmpdir) / "does_not_exist.jpg"
        res3 = agent.analyze(non_existent)
        assert res3.metadata_flag == MetadataState.MISSING.value
        assert "not found" in res3.reasoning.lower()


