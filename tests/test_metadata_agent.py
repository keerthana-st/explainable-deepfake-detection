    assert res.c2pa_details.signing_issuer == "OpenAI OpCo, LLC"
    assert res.c2pa_details.timestamp is not None
    assert len(res.c2pa_details.actions) > 0

    # Verify data source tag indicates real binary parsing
    assert "C2PA_JUMBF_STORE" in res.data_source_tag
    assert "VERIFIED_BINARY_EXTRACTION" in res.data_source_tag

    # Verify reasoning explicitly mentions cryptographic provenance and Disagreement Layer override
    assert "CRYPTOGRAPHIC PROVENANCE DISCLOSURE" in res.reasoning
