def test_xmp_creator_tool_ai_disclosed(agent):
    """Tests that XMP CreatorTool blocks with AI keywords trigger 'ai_disclosed'."""
    with tempfile.TemporaryDirectory() as tmpdir:
        xmp_path = Path(tmpdir) / "firefly_test.jpg"
        # Construct minimal JPEG with XMP packet
        img = Image.new("RGB", (150, 150), color=(80, 140, 200))
        img.save(xmp_path, format="JPEG")

        # Inject XMP packet into the JPEG binary
        xmp_payload = (
            b'<?xpacket begin="\xef\xbb\xbf" id="W5M0MpCehiHzreSzNTczkc9d"?>'
            b'<x:xmpmeta xmlns:x="adobe:ns:meta/">'
            b'<rdf:RDF xmlns:rdf="http://www.w3.org/1999/02/22-rdf-syntax-ns#">'
            b'<rdf:Description xmlns:xmp="http://ns.adobe.com/xap/1.0/">'
            b'<xmp:CreatorTool>Adobe Firefly 2.0</xmp:CreatorTool>'
            b'</rdf:Description>'
            b'</rdf:RDF>'
            b'</x:xmpmeta>'
            b'<?xpacket end="w"?>'
        )
        with open(xmp_path, "ab") as f:
            f.write(xmp_payload)

        parser = XmpMetadataParser()
        xmp_res = parser.parse(xmp_path)
        assert xmp_res["xmp_found"] is True
        assert xmp_res["ai_disclosed"] is True
        assert xmp_res["matched_tool"] == "Adobe Firefly"

        agent_res = agent.analyze(xmp_path)
        assert agent_res.metadata_flag == MetadataState.AI_DISCLOSED.value
        assert agent_res.disclosed_tool == "Adobe Firefly"


def test_c2pa_manifest_present_generator_unclear(agent):
    """
    Tests state 'manifest_present_generator_unclear' when a C2PA chunk exists
    without a resolvable recognized generator name.
    """
    with tempfile.TemporaryDirectory() as tmpdir:
        png_path = Path(tmpdir) / "unclear.png"
        img = Image.new("RGB", (100, 100), color=(20, 20, 20))
        img.save(png_path, format="PNG")

        # Append a custom caBX chunk before IEND
        with open(png_path, "rb") as f:
            data = f.read()

        iend_pos = data.find(b"IEND")
        dummy_cabx = b"jumdc2pa\x00\x00urn:c2pa:proprietary-internal-id"
        chunk_len = struct.pack(">I", len(dummy_cabx))
        chunk_type = b"caBX"
        crc = struct.pack(">I", zlib.crc32(chunk_type + dummy_cabx) & 0xffffffff)
        modified = data[:iend_pos - 4] + chunk_len + chunk_type + dummy_cabx + crc + data[iend_pos - 4:]

        with open(png_path, "wb") as f:
            f.write(modified)

        res = agent.analyze(png_path)
        assert res.metadata_flag == MetadataState.MANIFEST_PRESENT_GENERATOR_UNCLEAR.value
        assert res.is_unclear is True
        assert res.disclosed_tool is None
        assert "MANIFEST PRESENT (GENERATOR UNCLEAR)" in res.reasoning


def test_disagreement_layer_arbitration_rule(agent):
    """
    Validates Disagreement Layer interaction specification:
    - When metadata_flag == 'ai_disclosed': Cryptographic provenance OVERRIDES
      probabilistic visual scores even if both Frequency and Classifier predict REAL.
    - When metadata_flag != 'ai_disclosed': Metadata NEVER overrides probabilistic scores.
    """
    def arbitrate_decision(freq_suspicious: bool, cls_verdict: str, meta_result: MetadataResult):
        if meta_result.is_ai_disclosed:
            if not freq_suspicious and cls_verdict == "REAL":
                return "PROVENANCE_OVERRIDE", "FAKE"
            return "CONVERGENT_AI", "FAKE"
        else:
            if freq_suspicious and cls_verdict == "FAKE":
                return "CONVERGENT_VISUAL", "FAKE"
            elif not freq_suspicious and cls_verdict == "REAL":
                return "CONVERGENT_VISUAL", "REAL"
            elif freq_suspicious and cls_verdict == "REAL":
                return "FALSE_POSITIVE_RESOLVED", "REAL"
            else:
                return "DIFFUSION_BLINDSPOT_RESOLVED", "FAKE"

    # Case A: Visuals say REAL + REAL, but metadata discloses AI -> PROVENANCE OVERRIDE to FAKE
    res_ai = MetadataResult(
        metadata_flag=MetadataState.AI_DISCLOSED.value,
        disclosed_tool="ChatGPT c2pa-rs/0.28.4",
        raw_manifest_data={},
        reasoning="Cryptographic disclosure",
        data_source_tag="[C2PA]",
    )
    status, final = arbitrate_decision(freq_suspicious=False, cls_verdict="REAL", meta_result=res_ai)
    assert status == "PROVENANCE_OVERRIDE"
    assert final == "FAKE"

    # Case B: Metadata missing -> visual consensus prevails
    res_missing = MetadataResult(
        metadata_flag=MetadataState.MISSING.value,
        disclosed_tool=None,
        raw_manifest_data={},
        reasoning="No metadata",
        data_source_tag="[NONE]",
    )
    status_b, final_b = arbitrate_decision(freq_suspicious=False, cls_verdict="REAL", meta_result=res_missing)
    assert status_b == "CONVERGENT_VISUAL"
    assert final_b == "REAL"

    # Case C: Metadata unclear -> does NOT override
    res_unclear = MetadataResult(
        metadata_flag=MetadataState.MANIFEST_PRESENT_GENERATOR_UNCLEAR.value,
        disclosed_tool=None,
        raw_manifest_data={},
        reasoning="Manifest present but unclear",
        data_source_tag="[C2PA]",
    )
    status_c, final_c = arbitrate_decision(freq_suspicious=False, cls_verdict="REAL", meta_result=res_unclear)
    assert status_c == "CONVERGENT_VISUAL"
    assert final_c == "REAL"
