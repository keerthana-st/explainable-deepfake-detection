def test_authentic_phone_camera_exif(agent):
    """
    Requirement 2: Test on a photo with intact camera EXIF.
    Must return 'present_no_ai_signal', NOT falsely flag as AI.
    """
    with tempfile.TemporaryDirectory() as tmpdir:
        cam_path = Path(tmpdir) / "camera_sample.jpg"
        img = Image.new("RGB", (200, 200), color=(100, 150, 200))
        exif = img.getexif()
        exif[0x010F] = "Sony"                                 # Make
        exif[0x0110] = "ILCE-7RM4"                            # Model (A7R IV)
        exif[0x0131] = "Imaging Edge Desktop"                 # Software
        exif[0x0132] = "2026:01:15 14:22:10"                 # DateTime
        exif[0xA434] = "FE 24-70mm F2.8 GM II"               # LensModel
        img.save(cam_path, format="JPEG", exif=exif)

        res = agent.analyze(cam_path)

        assert res.metadata_flag == MetadataState.PRESENT_NO_AI_SIGNAL.value
        assert res.disclosed_tool is None
        assert res.is_authentic_supporting is True
        assert res.is_ai_disclosed is False
        assert "Sony" in res.exif_summary.get("make", "")
        assert "ILCE-7RM4" in res.exif_summary.get("model", "")
        assert "METADATA PRESENT (NO AI DISCLOSURE)" in res.reasoning
        # Must explicitly state that presence of EXIF does not prove authenticity
        assert "does not prove authenticity" in res.reasoning


