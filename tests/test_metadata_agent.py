def test_genuine_c2pa_chatgpt_manifest(agent, chatgpt_image_path):
    """
    Requirement 1: Test on a genuine ChatGPT/DALL-E 3 image.
    Must correctly extract specific claim_generator, issuer, and actions, not just 'manifest exists'.
    """
